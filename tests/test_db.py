"""Слой доступа к базе: одни и те же запросы на SQLite и на Postgres.

Без TEST_DATABASE_URL тесты идут на SQLite, с ним — на Postgres (см. conftest.py).
"""
import pytest

from app.db import POSTGRES, SQLITE, Duplicate, open_database, prepare, schema_for, to_dialect

SCHEMA = """
create table if not exists things (
    id {id},
    name text not null unique,
    weight {real} not null,
    created_at bigint not null
);
"""


def test_placeholders_are_written_once_and_translated_for_postgres():
    sql = "select id from things where name = ? and weight > ?"

    assert to_dialect(sql, SQLITE) == sql
    assert to_dialect(sql, POSTGRES) == "select id from things where name = %s and weight > %s"


def test_schema_types_follow_the_database():
    assert "id integer primary key," in schema_for(SCHEMA, SQLITE)
    assert "id bigint generated by default as identity primary key," in schema_for(SCHEMA, POSTGRES)
    assert "weight double precision" in schema_for(SCHEMA, POSTGRES)


@pytest.fixture
def things(database):
    prepare(database, SCHEMA)
    return database


def add(database, name, weight=1.5):
    with database.transaction() as db:
        return db.one("insert into things (name, weight, created_at) values (?, ?, ?) returning id",
                      (name, weight, 1_780_000_000))[0]


def test_insert_returns_the_new_id(things):
    first, second = add(things, "a"), add(things, "b")

    assert second > first


def test_values_come_back_with_their_types(things):
    add(things, "кресло", 886.13)

    with things.transaction() as db:
        assert db.one("select name, weight, created_at from things where name = ?", ("кресло",)) == \
            ("кресло", 886.13, 1_780_000_000)


def test_unique_violation_becomes_duplicate(things):
    add(things, "a")

    with pytest.raises(Duplicate):
        add(things, "a")
    assert add(things, "b")  # после ошибки база работает дальше


def test_failed_transaction_is_rolled_back(things):
    with pytest.raises(RuntimeError):
        with things.transaction() as db:
            db.execute("insert into things (name, weight, created_at) values (?, ?, ?)", ("x", 1.0, 1))
            raise RuntimeError("сбой посреди транзакции")

    with things.transaction() as db:
        assert db.all("select name from things") == []


def test_data_survives_reopening(things, database_target):
    add(things, "a")
    things.close()

    again = open_database(*database_target)
    try:
        with again.transaction() as db:
            assert db.all("select name from things") == [("a",)]
    finally:
        again.close()


def test_dialect_matches_the_target(database, database_target):
    url, _ = database_target
    assert database.dialect == (POSTGRES if url else SQLITE)
