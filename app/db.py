"""Доступ к базе: файл SQLite или Postgres (если задан DATABASE_URL).

Один слой для обеих баз:
- запросы пишутся один раз с плейсхолдером «?», для Postgres он меняется на «%s»;
  параметры всегда передаются отдельно, строки в SQL не склеиваются;
- в схеме типы ключа и дробных чисел подставляются под базу: {id}, {real};
- время хранится целым числом секунд Unix (bigint) в обеих базах;
- новый id возвращает INSERT … RETURNING id (SQLite 3.35+ и Postgres);
- нарушение уникальности в обеих базах превращается в Duplicate.
"""
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Iterator, Protocol

SQLITE = "sqlite"
POSTGRES = "postgres"
TYPES = {
    SQLITE: {"id": "integer primary key", "real": "double precision"},
    POSTGRES: {"id": "bigint generated by default as identity primary key", "real": "double precision"},
}


class Duplicate(Exception):
    """Нарушена уникальность: например, такой логин уже есть."""


def to_dialect(sql: str, dialect: str) -> str:
    return sql.replace("?", "%s") if dialect == POSTGRES else sql


def schema_for(schema: str, dialect: str) -> str:
    return schema.format(**TYPES[dialect])


class Session:
    """Запросы внутри одной транзакции."""

    def __init__(self, connection, dialect: str):
        self._connection = connection
        self.dialect = dialect

    def execute(self, sql: str, params: tuple = ()) -> None:
        self._connection.execute(to_dialect(sql, self.dialect), params)

    def all(self, sql: str, params: tuple = ()) -> list[tuple]:
        return [tuple(row) for row in self._connection.execute(to_dialect(sql, self.dialect), params).fetchall()]

    def one(self, sql: str, params: tuple = ()) -> tuple | None:
        rows = self.all(sql, params)  # строки забираются целиком: так INSERT … RETURNING в SQLite завершается
        return rows[0] if rows else None


class Database(Protocol):
    dialect: str

    def transaction(self) -> Iterator[Session]: ...

    def close(self) -> None: ...


class SqliteDatabase:
    """Каждая транзакция открывает своё соединение: хранилища можно звать из разных потоков."""

    dialect = SQLITE

    def __init__(self, path: Path):
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)

    @contextmanager
    def transaction(self) -> Iterator[Session]:
        connection = sqlite3.connect(self.path)
        try:
            connection.execute("pragma foreign_keys = on")
            with connection:  # фиксирует изменения или откатывает их при ошибке
                yield Session(connection, SQLITE)
        except sqlite3.IntegrityError as error:
            if "UNIQUE" in str(error):
                raise Duplicate(str(error)) from error
            raise
        finally:
            connection.close()

    def close(self) -> None:
        pass


class PostgresDatabase:
    """Пул из нескольких соединений: открывать новое на каждый запрос к облачной базе долго."""

    dialect = POSTGRES

    def __init__(self, url: str):
        from psycopg_pool import ConnectionPool

        self.pool = ConnectionPool(url, min_size=1, max_size=4, open=True, kwargs={"connect_timeout": 10})
        self.pool.wait(timeout=30)  # без базы сервер не стартует, и ошибка видна сразу

    @contextmanager
    def transaction(self) -> Iterator[Session]:
        from psycopg import errors

        try:
            with self.pool.connection() as connection:  # фиксирует изменения или откатывает их при ошибке
                yield Session(connection, POSTGRES)
        except errors.UniqueViolation as error:
            raise Duplicate(str(error)) from error

    def close(self) -> None:
        if not self.pool.closed:
            self.pool.close()


def open_database(url: str | None, path: Path) -> Database:
    """Postgres, если задан адрес, иначе файл SQLite."""
    return PostgresDatabase(url) if url else SqliteDatabase(path)


def prepare(database: Database, schema: str) -> None:
    """Создаёт таблицы, которых ещё нет."""
    with database.transaction() as db:
        for statement in schema_for(schema, database.dialect).split(";"):
            if statement.strip():
                db.execute(statement)
